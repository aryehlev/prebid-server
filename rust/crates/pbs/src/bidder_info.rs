/// Go `loadBidderInfo` minus the builder: parse the embedded YAML for `name`.
pub fn load(name: &str) -> Result<BidderInfo, String> {
    let data = raw(name).ok_or_else(|| format!("open bidder-info/{name}.yaml: file does not exist"))?;
    serde_yaml::from_str(data).map_err(|e| format!("error parsing config for bidder {name}: {e}"))
}
