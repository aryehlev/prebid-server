//! Go `config.BidderInfo` as far as the seller reads it, loaded from the embedded
//! `bidder-info/*.yaml` (the seller's `//go:embed bidder-info/*`, copied from the Prebid module
//! by `scripts/copy-prebid-files.sh`).
//!
//! The seller's `loadBidderInfo` unmarshals the YAML as is: an alias file with no `endpoint` of
//! its own keeps an empty endpoint (27 of the 77 alias files). No alias resolution is done here
//! either.

use serde::Deserialize;

use crate::config;

/// Go `config.AdapterXAPI`.
#[derive(Debug, Clone, Default, Deserialize)]
pub struct Xapi {
    #[serde(default)]
    pub username: String,
    #[serde(default)]
    pub password: String,
    #[serde(default)]
    pub tracker: String,
}

/// The `BidderInfo` fields the seller uses (`prebid_buyer.go`).
#[derive(Debug, Clone, Default, Deserialize)]
pub struct BidderInfo {
    #[serde(default)]
    pub endpoint: String,
    #[serde(default, rename = "extra_info")]
    pub extra_adapter_info: String,
    #[serde(default, rename = "platform_id")]
    pub platform_id: String,
    #[serde(default, rename = "app_secret")]
    pub app_secret: String,
    #[serde(default)]
    pub xapi: Xapi,
    /// `endpointCompression`: `GZIP` makes the seller gzip the request body.
    #[serde(default, rename = "endpointCompression")]
    pub endpoint_compression: String,
    #[serde(default, rename = "gvlVendorID")]
    pub gvl_vendor_id: u16,
}

impl BidderInfo {
    /// Go: `strings.ToLower(bidderInfo.EndpointCompression) == "gzip"`.
    pub fn gzip_requests(&self) -> bool {
        self.endpoint_compression.eq_ignore_ascii_case("gzip")
    }

    /// The `config.Adapter` the seller builds from it (`loadBidderInfo`).
    pub fn adapter_config(&self) -> config::Adapter {
        config::Adapter {
            endpoint: self.endpoint.clone(),
            extra_adapter_info: self.extra_adapter_info.clone(),
            xapi: config::AdapterXapi {
                username: self.xapi.username.clone(),
                password: self.xapi.password.clone(),
                tracker: self.xapi.tracker.clone(),
            },
            platform_id: self.platform_id.clone(),
            app_secret: self.app_secret.clone(),
        }
    }
}

